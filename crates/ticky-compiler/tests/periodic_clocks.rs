use ticky_compiler::testrun::{run_tests, Harness, PVal};
use ticky_compiler::{compile, Opt, Options};
use ticky_syntax::ast::PortDir;

#[test]
fn independent_pump_controllers_share_sample_and_commit_pulses() {
    let src = include_str!("../../../examples/pump-bank.ticky");
    for opt in [Opt::Speed, Opt::Size] {
        for checks in [false, true] {
            let c = compile(
                src,
                &Options {
                    opt,
                    checks,
                    ..Default::default()
                },
            )
            .unwrap();
            // Frozen 09a1940 emitted 44 without checks and 52 with checks.
            assert_eq!(
                c.cg.netlist
                    .entities
                    .iter()
                    .filter(|e| e.kind.is_combinator())
                    .count(),
                if checks { 48 } else { 40 }
            );
            assert_eq!(
                c.cg.blocks.iter().map(|b| b.period).collect::<Vec<_>>(),
                [6, 6, 6, 12]
            );
            assert!(c.cg.netlist.validate(true).is_empty());
            for result in run_tests(&c, src) {
                assert!(
                    result.failure.is_none(),
                    "{}: {:?}",
                    result.name,
                    result.failure
                );
            }
        }
    }
}

#[test]
fn shared_phases_match_frozen_tick_trace_through_restarts_and_dynamic_waits() {
    let src = include_str!("fixtures/periodic-phases.ticky");
    // Generated by frozen 09a1940, before phase sharing. The first block has
    // only own-state sources; the next two wrap their commits to phase 1 and
    // require warm-up suppression. Other blocks commit at different phases
    // and rates. Inputs and dynamic wait lengths change every tick.
    for opt in [Opt::Speed, Opt::Size] {
        for checks in [false, true] {
            let baseline = if checks {
                include_str!("fixtures/periodic-phases-true.txt")
            } else {
                include_str!("fixtures/periodic-phases-false.txt")
            };
            let c = compile(
                src,
                &Options {
                    opt,
                    checks,
                    ..Default::default()
                },
            )
            .unwrap();
            assert!(c.cg.netlist.validate(true).is_empty());
            let mut h = Harness::new(&c);
            let ports: Vec<_> = c
                .program
                .ports
                .iter()
                .enumerate()
                .filter(|(_, p)| p.dir == PortDir::Output)
                .map(|(i, _)| i)
                .collect();
            for (tick, row) in baseline.lines().skip(1).enumerate() {
                let tick = tick as i32;
                h.set(
                    c.program.port_index("x").unwrap(),
                    PVal::Int(tick * 17 % 41 - 9),
                );
                h.set(
                    c.program.port_index("delay").unwrap(),
                    PVal::Int(tick * 7 % 12),
                );
                if let Some((_, on)) = [
                    (17, false),
                    (18, true),
                    (41, false),
                    (48, true),
                    (91, false),
                    (110, true),
                ]
                .iter()
                .find(|(t, _)| *t == tick)
                {
                    h.sim.set_constant_on(c.cg.run_switch, *on);
                }
                let expected: Vec<_> = row
                    .split_whitespace()
                    .skip(1)
                    .map(|s| PVal::Int(s.parse().unwrap()))
                    .collect();
                let actual: Vec<_> = ports.iter().map(|&p| h.get(p)).collect();
                assert_eq!(
                    actual, expected,
                    "tick {tick}, opt {opt:?}, checks {checks}"
                );
                h.sim.step();
            }
        }
    }
}
